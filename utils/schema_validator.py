"""Discover the reporting views and validate AI-generated column references."""
import re
from sqlalchemy import inspect
from utils.query_validator import ALLOWED_VIEWS


def get_database_schema(engine):
    inspector = inspect(engine)
    available_views = set(inspector.get_view_names(schema="finance_ops"))
    database_schema = {}
    for view in sorted(ALLOWED_VIEWS & available_views):
        columns = inspector.get_columns(view, schema="finance_ops")
        database_schema[view] = [column["name"] for column in columns]
    if not database_schema:
        raise RuntimeError("No approved finance_ops reporting views were found. Check the database schema.")
    return database_schema


def build_schema_context(database_schema):
    return "\n\n".join(
        f"finance_ops.{view}:\n  Columns: {', '.join(columns)}"
        for view, columns in sorted(database_schema.items())
    )


def validate_columns(query, database_schema):
    """Check qualified view names and referenced column identifiers.

    This conservative validator supports the straightforward SELECT patterns
    generated by the app. If the query is too complex to validate confidently,
    it rejects it instead of guessing.
    """
    query_lower = query.lower()
    views = re.findall(r"finance_ops\.([a-zA-Z_][a-zA-Z0-9_]*)", query_lower)
    if not views:
        raise ValueError("No finance_ops view found in query.")
    for view in views:
        if view not in database_schema:
            raise ValueError(f"Unknown or unavailable finance_ops view: {view}")

    # Strip literals/comments, then check common column tokens against all
    # available view columns and SQL grammar tokens. SQL execution remains the
    # final syntax/type check.
    cleaned = re.sub(r"--[^\n\r]*|/\*.*?\*/", " ", query_lower, flags=re.DOTALL)
    cleaned = re.sub(r"'(?:''|[^'])*'", "''", cleaned)
    cleaned = re.sub(r"\bextract\s*\(\s*(year|quarter|month|week|day|dow|doy)\b", "extract(__date_part__", cleaned)
    columns = {c.lower() for cols in database_schema.values() for c in cols}
    aliases = set(re.findall(r"\bas\s+([a-z_][a-z0-9_]*)", cleaned))
    tokens = re.findall(r"\b[a-z_][a-z0-9_]*\b", cleaned)
    allowed_tokens = {
        "select", "from", "where", "and", "or", "as", "sum", "avg", "count", "min", "max",
        "group", "by", "order", "limit", "offset", "desc", "asc", "having", "distinct",
        "case", "when", "then", "else", "end", "date", "current_date", "interval", "null",
        "is", "not", "in", "between", "over", "partition", "filter", "on", "true", "false",
        "finance_ops", "round", "extract", "coalesce", "cast", "numeric", "text", "integer",
        "bigint", "timestamp", "greatest", "least", "count", "__date_part__",
        "date_trunc", "date_part", "lower", "upper", "trim", "abs", "nullif",
        "to_char", "substring", "length", "replace", "floor", "ceil", "ceiling",
        "row_number", "rank", "dense_rank", "lag", "lead", "first_value",
        "last_value", "string_agg", "array_agg", "bool_and", "bool_or",
        "union", "all", "any", "exists", "like", "ilike", "escape",
    } | set(database_schema) | aliases
    # Column checking is intentionally best-effort because SQL permits qualified
    # column references and aliases. Reject tokens that are clearly identifiers
    # but not known columns, aliases, SQL keywords/functions, or approved views.
    for token in tokens:
        if token in allowed_tokens or token in columns or token.isdigit():
            continue
        # Schema/view names already validated above; quoted string content was removed.
        if token in {v.lower() for v in views}:
            continue
        raise ValueError(f"Unrecognized SQL identifier '{token}'. Check the view columns or simplify the question.")
    return True
