-- Fresh-database bootstrap for the Finance Operations Analytics project.
-- WARNING: Run only in a NEW/EMPTY project database. Do not run this against
-- an existing database without reviewing and backing it up first.

CREATE SCHEMA IF NOT EXISTS finance_ops;

CREATE TABLE IF NOT EXISTS finance_ops.accounts_master (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_name TEXT NOT NULL UNIQUE,
    account_type TEXT NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'INR'
);

CREATE TABLE IF NOT EXISTS finance_ops.customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT NOT NULL,
    industry TEXT NOT NULL,
    credit_limit NUMERIC(14,2) NOT NULL CHECK (credit_limit >= 0)
);

CREATE TABLE IF NOT EXISTS finance_ops.vendors (
    vendor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_name TEXT NOT NULL,
    category TEXT NOT NULL,
    payment_terms INTEGER NOT NULL CHECK (payment_terms > 0)
);

CREATE TABLE IF NOT EXISTS finance_ops.budget (
    budget_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department TEXT NOT NULL,
    month DATE NOT NULL,
    budget_amount NUMERIC(14,2) NOT NULL CHECK (budget_amount >= 0),
    CONSTRAINT uq_budget_department_month UNIQUE (department, month)
);

CREATE TABLE IF NOT EXISTS finance_ops.sales_transactions (
    sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES finance_ops.customers(customer_id),
    sale_date DATE NOT NULL,
    invoice_amount NUMERIC(14,2) NOT NULL CHECK (invoice_amount >= 0),
    tax_amount NUMERIC(14,2) NOT NULL CHECK (tax_amount >= 0),
    total_amount NUMERIC(14,2) NOT NULL CHECK (total_amount >= 0),
    status TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS finance_ops.receivables (
    receivable_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id BIGINT NOT NULL UNIQUE REFERENCES finance_ops.sales_transactions(sale_id) ON DELETE CASCADE,
    customer_id BIGINT NOT NULL REFERENCES finance_ops.customers(customer_id),
    invoice_date DATE NOT NULL,
    due_date DATE NOT NULL,
    amount_due NUMERIC(14,2) NOT NULL CHECK (amount_due >= 0),
    amount_received NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (amount_received >= 0 AND amount_received <= amount_due),
    status TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS finance_ops.expense_entries (
    expense_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_id BIGINT NOT NULL REFERENCES finance_ops.vendors(vendor_id),
    expense_date DATE NOT NULL,
    department TEXT NOT NULL,
    expense_amount NUMERIC(14,2) NOT NULL CHECK (expense_amount >= 0)
);

CREATE TABLE IF NOT EXISTS finance_ops.payables (
    payable_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expense_id BIGINT NOT NULL UNIQUE REFERENCES finance_ops.expense_entries(expense_id) ON DELETE CASCADE,
    vendor_id BIGINT NOT NULL REFERENCES finance_ops.vendors(vendor_id),
    bill_date DATE NOT NULL,
    due_date DATE NOT NULL,
    amount_due NUMERIC(14,2) NOT NULL CHECK (amount_due >= 0),
    amount_paid NUMERIC(14,2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0 AND amount_paid <= amount_due),
    status TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS finance_ops.bank_transactions (
    transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES finance_ops.accounts_master(account_id),
    transaction_date DATE NOT NULL,
    transaction_type TEXT NOT NULL CHECK (transaction_type IN ('inflow', 'outflow')),
    reference_type TEXT NOT NULL,
    reference_id BIGINT,
    amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
    description TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS ix_sales_date ON finance_ops.sales_transactions(sale_date);
CREATE INDEX IF NOT EXISTS ix_expenses_date ON finance_ops.expense_entries(expense_date);
CREATE INDEX IF NOT EXISTS ix_receivables_due_date ON finance_ops.receivables(due_date);
CREATE INDEX IF NOT EXISTS ix_payables_due_date ON finance_ops.payables(due_date);
CREATE INDEX IF NOT EXISTS ix_bank_transactions_date ON finance_ops.bank_transactions(transaction_date);

CREATE OR REPLACE VIEW finance_ops.vw_monthly_revenue AS
SELECT date_trunc('month', sale_date)::date AS month,
       SUM(invoice_amount)::numeric(14,2) AS invoice_amount,
       SUM(tax_amount)::numeric(14,2) AS tax_amount,
       SUM(total_amount)::numeric(14,2) AS total_revenue
FROM finance_ops.sales_transactions
GROUP BY date_trunc('month', sale_date)::date;

CREATE OR REPLACE VIEW finance_ops.vw_monthly_expenses AS
SELECT date_trunc('month', expense_date)::date AS month,
       department,
       SUM(expense_amount)::numeric(14,2) AS total_expense
FROM finance_ops.expense_entries
GROUP BY date_trunc('month', expense_date)::date, department;

CREATE OR REPLACE VIEW finance_ops.vw_monthly_closing_summary AS
WITH revenue AS (
    SELECT month, SUM(total_revenue) AS total_revenue
    FROM finance_ops.vw_monthly_revenue GROUP BY month
), expenses AS (
    SELECT month, SUM(total_expense) AS total_expense
    FROM finance_ops.vw_monthly_expenses GROUP BY month
)
SELECT COALESCE(r.month, e.month) AS month,
       COALESCE(r.total_revenue, 0)::numeric(14,2) AS total_revenue,
       COALESCE(e.total_expense, 0)::numeric(14,2) AS total_expense,
       (COALESCE(r.total_revenue, 0) - COALESCE(e.total_expense, 0))::numeric(14,2) AS net_profit
FROM revenue r FULL OUTER JOIN expenses e ON e.month = r.month;

CREATE OR REPLACE VIEW finance_ops.vw_budget_vs_actual AS
WITH actual AS (
    SELECT date_trunc('month', expense_date)::date AS month, department,
           SUM(expense_amount) AS actual_amount
    FROM finance_ops.expense_entries
    GROUP BY date_trunc('month', expense_date)::date, department
)
SELECT b.month, b.department, b.budget_amount,
       COALESCE(a.actual_amount, 0)::numeric(14,2) AS actual_amount,
       (COALESCE(a.actual_amount, 0) - b.budget_amount)::numeric(14,2) AS variance_amount,
       CASE WHEN b.budget_amount = 0 THEN NULL
            ELSE ((COALESCE(a.actual_amount, 0) - b.budget_amount) / b.budget_amount * 100)::numeric(14,2)
       END AS variance_pct
FROM finance_ops.budget b
LEFT JOIN actual a ON a.month = b.month AND a.department = b.department;

CREATE OR REPLACE VIEW finance_ops.vw_receivables_aging AS
SELECT r.receivable_id, r.sale_id, r.customer_id, c.customer_name,
       r.invoice_date, r.due_date, r.amount_due, r.amount_received,
       (r.amount_due - r.amount_received)::numeric(14,2) AS outstanding_amount,
       CASE WHEN r.amount_due <= r.amount_received THEN 'Closed'
            WHEN r.due_date >= CURRENT_DATE THEN 'Not Due'
            WHEN CURRENT_DATE - r.due_date <= 30 THEN '1-30 Days'
            WHEN CURRENT_DATE - r.due_date <= 60 THEN '31-60 Days'
            WHEN CURRENT_DATE - r.due_date <= 90 THEN '61-90 Days'
            ELSE '90+ Days' END AS aging_bucket
FROM finance_ops.receivables r
JOIN finance_ops.customers c ON c.customer_id = r.customer_id;

CREATE OR REPLACE VIEW finance_ops.vw_payables_aging AS
SELECT p.payable_id, p.expense_id, p.vendor_id, v.vendor_name,
       p.bill_date, p.due_date, p.amount_due, p.amount_paid,
       (p.amount_due - p.amount_paid)::numeric(14,2) AS outstanding_amount,
       CASE WHEN p.amount_due <= p.amount_paid THEN 'Closed'
            WHEN p.due_date >= CURRENT_DATE THEN 'Not Due'
            WHEN CURRENT_DATE - p.due_date <= 30 THEN '1-30 Days'
            WHEN CURRENT_DATE - p.due_date <= 60 THEN '31-60 Days'
            WHEN CURRENT_DATE - p.due_date <= 90 THEN '61-90 Days'
            ELSE '90+ Days' END AS aging_bucket
FROM finance_ops.payables p
JOIN finance_ops.vendors v ON v.vendor_id = p.vendor_id;

CREATE OR REPLACE VIEW finance_ops.vw_cash_flow AS
SELECT transaction_id, account_id, transaction_date, transaction_type,
       reference_type, reference_id, amount, description,
       CASE WHEN transaction_type = 'inflow' THEN amount ELSE 0 END::numeric(14,2) AS cash_in,
       CASE WHEN transaction_type = 'outflow' THEN amount ELSE 0 END::numeric(14,2) AS cash_out
FROM finance_ops.bank_transactions;

CREATE OR REPLACE VIEW finance_ops.vw_daily_cash_summary AS
SELECT transaction_date,
       SUM(cash_in)::numeric(14,2) AS total_inflow,
       SUM(cash_out)::numeric(14,2) AS total_outflow,
       (SUM(cash_in) - SUM(cash_out))::numeric(14,2) AS net_cash_flow
FROM finance_ops.vw_cash_flow
GROUP BY transaction_date;

CREATE OR REPLACE VIEW finance_ops.vw_running_cash_balance AS
SELECT transaction_date, transaction_id, transaction_type, reference_type,
       reference_id, amount,
       SUM(CASE WHEN transaction_type = 'inflow' THEN amount ELSE -amount END)
           OVER (ORDER BY transaction_date, transaction_id ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW)::numeric(14,2) AS running_balance
FROM finance_ops.bank_transactions;

CREATE OR REPLACE VIEW finance_ops.vw_cash_forecast_30_days AS
WITH expected AS (
    SELECT due_date AS forecast_date, (amount_due - amount_received) AS expected_inflow, 0::numeric AS expected_outflow
    FROM finance_ops.receivables
    WHERE amount_due > amount_received AND due_date BETWEEN CURRENT_DATE AND CURRENT_DATE + 30
    UNION ALL
    SELECT due_date AS forecast_date, 0::numeric AS expected_inflow, (amount_due - amount_paid) AS expected_outflow
    FROM finance_ops.payables
    WHERE amount_due > amount_paid AND due_date BETWEEN CURRENT_DATE AND CURRENT_DATE + 30
)
SELECT forecast_date, SUM(expected_inflow)::numeric(14,2) AS expected_inflow,
       SUM(expected_outflow)::numeric(14,2) AS expected_outflow,
       (SUM(expected_inflow) - SUM(expected_outflow))::numeric(14,2) AS net_expected_cash_flow
FROM expected GROUP BY forecast_date;

CREATE OR REPLACE VIEW finance_ops.vw_dso AS
WITH monthly_sales AS (
    SELECT date_trunc('month', sale_date)::date AS month, SUM(total_amount) AS total_credit_sales
    FROM finance_ops.sales_transactions GROUP BY date_trunc('month', sale_date)::date
), monthly_ar AS (
    SELECT date_trunc('month', invoice_date)::date AS month,
           AVG(amount_due - amount_received) AS avg_receivable
    FROM finance_ops.receivables GROUP BY date_trunc('month', invoice_date)::date
)
SELECT s.month, COALESCE(a.avg_receivable, 0)::numeric(14,2) AS avg_receivable,
       s.total_credit_sales::numeric(14,2) AS total_credit_sales,
       CASE WHEN s.total_credit_sales = 0 THEN NULL
            ELSE (COALESCE(a.avg_receivable, 0) / s.total_credit_sales * EXTRACT(DAY FROM (s.month + INTERVAL '1 month - 1 day')))::numeric(14,2)
       END AS dso
FROM monthly_sales s LEFT JOIN monthly_ar a ON a.month = s.month;

CREATE OR REPLACE VIEW finance_ops.vw_dpo AS
WITH monthly_purchases AS (
    SELECT date_trunc('month', expense_date)::date AS month, SUM(expense_amount) AS total_purchases
    FROM finance_ops.expense_entries GROUP BY date_trunc('month', expense_date)::date
), monthly_ap AS (
    SELECT date_trunc('month', bill_date)::date AS month,
           AVG(amount_due - amount_paid) AS avg_payable
    FROM finance_ops.payables GROUP BY date_trunc('month', bill_date)::date
)
SELECT p.month, COALESCE(a.avg_payable, 0)::numeric(14,2) AS avg_payable,
       p.total_purchases::numeric(14,2) AS total_purchases,
       CASE WHEN p.total_purchases = 0 THEN NULL
            ELSE (COALESCE(a.avg_payable, 0) / p.total_purchases * EXTRACT(DAY FROM (p.month + INTERVAL '1 month - 1 day')))::numeric(14,2)
       END AS dpo
FROM monthly_purchases p LEFT JOIN monthly_ap a ON a.month = p.month;

CREATE OR REPLACE VIEW finance_ops.vw_top_overdue_customers AS
SELECT customer_name, SUM(outstanding_amount)::numeric(14,2) AS total_overdue
FROM finance_ops.vw_receivables_aging
WHERE outstanding_amount > 0 AND due_date < CURRENT_DATE
GROUP BY customer_name ORDER BY total_overdue DESC;

CREATE OR REPLACE VIEW finance_ops.vw_top_outstanding_vendors AS
SELECT vendor_name, SUM(outstanding_amount)::numeric(14,2) AS total_outstanding
FROM finance_ops.vw_payables_aging
WHERE outstanding_amount > 0
GROUP BY vendor_name ORDER BY total_outstanding DESC;
